"""Application settings.

Settings are read from environment variables prefixed with ``VEYRA_`` and,
when present, from the environment file written by the installer
(``/etc/veyra/veyra.env``). Secrets are never given defaults that would work
in production: the database URL must be supplied explicitly.
"""

from __future__ import annotations

import os
from enum import StrEnum
from functools import lru_cache
from pathlib import Path
from typing import Annotated

from pydantic import Field, field_validator
from pydantic_settings import BaseSettings, NoDecode, SettingsConfigDict

DEFAULT_ENV_FILE = Path("/etc/veyra/veyra.env")


class Environment(StrEnum):
    DEVELOPMENT = "development"
    TEST = "test"
    PRODUCTION = "production"


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_prefix="VEYRA_",
        env_file=os.environ.get("VEYRA_ENV_FILE", str(DEFAULT_ENV_FILE)),
        env_file_encoding="utf-8",
        extra="ignore",
    )

    environment: Environment = Environment.PRODUCTION

    # --- Database -------------------------------------------------------------
    database_url: str = Field(
        default="",
        description="SQLAlchemy URL, e.g. postgresql+psycopg://veyra@/veyra?host=/run/postgresql",
    )
    database_pool_size: int = 10

    # --- Paths ----------------------------------------------------------------
    config_dir: Path = Path("/etc/veyra")
    data_dir: Path = Path("/var/lib/veyra")
    log_dir: Path = Path("/var/log/veyra")
    module_paths: Annotated[list[Path], NoDecode] = Field(
        default_factory=lambda: [Path("/opt/veyra/modules")]
    )
    template_paths: Annotated[list[Path], NoDecode] = Field(
        default_factory=lambda: [Path("/opt/veyra/provisioning/templates")]
    )

    # --- Sessions & security --------------------------------------------------
    session_ttl_hours: int = 12
    session_idle_minutes: int = 60
    cookie_secure: bool = True
    login_rate_limit_per_minute: int = 10
    account_lockout_threshold: int = 10
    account_lockout_minutes: int = 15
    trusted_proxy_count: int = 1
    # Expired and revoked sessions are kept this long (they are evidence for
    # the audit trail), then deleted by the worker.
    session_retention_days: int = 30
    # Validity of administrator- and CLI-issued password reset links.
    password_reset_ttl_hours: int = 24
    # Bearer tokens for the Companion extension (ADR 0015): idle expiry after
    # the last use, and a hard maximum age from creation.
    companion_token_idle_days: int = 30
    companion_token_max_days: int = 180

    # --- Modules --------------------------------------------------------------
    # Unsigned modules may only be loaded in development. Never enable this
    # in production; the setting is ignored when environment == production.
    allow_unsigned_modules: bool = False

    # --- Secrets --------------------------------------------------------------
    # 256-bit key that encrypts SIP secrets, sensitive revision files and
    # (later) MFA secrets at rest. Generated by the installer; defaults to
    # <config_dir>/secrets/installation.key. See veyra.core.security.crypto.
    installation_key_file: Path | None = None

    # --- Telephony ------------------------------------------------------------
    telephony_engine: str = "asterisk"
    asterisk_ari_url: str = "http://127.0.0.1:8088/ari"
    asterisk_ari_username: str = "veyra"
    asterisk_ari_password_file: Path = Path("/etc/veyra/secrets/ari_password")
    # Directory that Asterisk's managed stub files #tryinclude. Written only
    # by the deployer service (never by the API process).
    asterisk_config_dir: Path = Path("/etc/asterisk/veyra")
    # "Deploy when no calls are active" waits at most this long, then deploys.
    deploy_idle_timeout_minutes: int = 30
    # The script Asterisk hands voicemail notifications to (``mailcmd`` in the
    # generated voicemail.conf); it writes them into the mail queue
    # (docs/VOICEMAIL_IVR.md §2). Shipped with the release.
    mailqueue_command: str = "/opt/veyra/current/installer/bin/veyra-mailqueue"

    # --- Companion extension ----------------------------------------------------
    # Where the installer leaves the packaged extension (zip, signed crx and
    # crx-info.json) for the download routes (docs/COMPANION.md §5).
    companion_dir: Path = Path("/opt/veyra/current/companion")

    # --- Updates --------------------------------------------------------------
    update_metadata_url: str = ""

    @field_validator("module_paths", "template_paths", mode="before")
    @classmethod
    def _split_paths(cls, value: object) -> object:
        if isinstance(value, str):
            return [Path(p) for p in value.split(":") if p]
        return value

    @property
    def is_production(self) -> bool:
        return self.environment == Environment.PRODUCTION

    @property
    def unsigned_modules_permitted(self) -> bool:
        return self.allow_unsigned_modules and not self.is_production

    def installed_release(self) -> str | None:
        """The release name written by the installer (``<version>-<revision>``),
        or None in development where no install state exists."""
        import json

        try:
            data = json.loads((self.config_dir / "install-state.json").read_text())
        except (OSError, ValueError):
            return None
        release = data.get("release") if isinstance(data, dict) else None
        return str(release) if release else None

    @property
    def installation_key_path(self) -> Path:
        return self.installation_key_file or self.config_dir / "secrets" / "installation.key"

    @property
    def trust_dir(self) -> Path:
        return self.config_dir / "trust"

    @property
    def prompts_dir(self) -> Path:
        """IVR prompts, one directory per organization slug; written by the API
        (uploads) and by Asterisk (recordings from phones)."""
        return self.data_dir / "prompts"

    @property
    def mailqueue_dir(self) -> Path:
        """Outgoing messages waiting for the worker (voicemail notifications
        from Asterisk and, later, other notifications)."""
        return self.data_dir / "mailqueue"

    @property
    def node_identity_file(self) -> Path:
        return self.config_dir / "node.json"


@lru_cache
def get_settings() -> Settings:
    return Settings()
