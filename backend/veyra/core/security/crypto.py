"""The installation key and encryption of secrets at rest.

Veyra keeps one symmetric key per installation, generated by the installer
and stored outside the database in ``/etc/veyra/secrets/installation.key``
(64 hexadecimal characters = 256 bits, mode 0640 root:veyra). Anything that
must be readable by the server but must not sit in the database in clear is
encrypted with it: SIP secrets of extensions, the sensitive files of
configuration revisions and, later, TOTP secrets (docs/MFA_DESIGN.md §6).

Encryption is AES-256-GCM with a random 96-bit nonce. The *purpose* string
is passed as associated data, so a ciphertext copied from one row to another
(or from one column to another) does not decrypt. Tokens are
``v1:<base64url(nonce || ciphertext || tag)>`` so the scheme can change
later without ambiguity.

A database dump alone therefore reveals no SIP credentials, and a backup of
``/etc/veyra`` alone reveals none either: both are needed. Losing the key
makes every encrypted value unrecoverable; see docs/EXTENSIONS.md §5 and
ADR 0014.
"""

from __future__ import annotations

import base64
import binascii
import hashlib
import os
import re
import secrets
from pathlib import Path

from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from veyra.core.config import Settings

KEY_BYTES = 32
NONCE_BYTES = 12
TOKEN_VERSION = "v1"  # noqa: S105 (format marker, not a secret)
KEY_FILE_MODE = 0o640
_HEX_KEY_RE = re.compile(r"^[0-9a-f]{64}$")


class InstallationKeyError(RuntimeError):
    """The installation key is missing or unusable."""


class DecryptionError(ValueError):
    """The token is malformed, was encrypted with another key, was altered,
    or is being used for a purpose other than the one it was created for."""


class InstallationKey:
    def __init__(self, raw: bytes) -> None:
        if len(raw) != KEY_BYTES:
            raise InstallationKeyError(f"installation key must be {KEY_BYTES} bytes")
        self._raw = raw
        self._aead = AESGCM(raw)

    # --- creation and storage ------------------------------------------------

    @classmethod
    def generate(cls) -> InstallationKey:
        return cls(secrets.token_bytes(KEY_BYTES))

    @classmethod
    def parse(cls, text: str) -> InstallationKey:
        value = text.strip().lower()
        if not _HEX_KEY_RE.match(value):
            raise InstallationKeyError(
                "installation key file must contain exactly 64 hexadecimal characters"
            )
        return cls(bytes.fromhex(value))

    @classmethod
    def load(cls, path: Path) -> InstallationKey:
        try:
            text = path.read_text(encoding="utf-8")
        except FileNotFoundError as e:
            raise InstallationKeyError(
                f"installation key {path} does not exist (the installer creates it; "
                "'veyra installation-key generate' creates one by hand)"
            ) from e
        except PermissionError as e:
            raise InstallationKeyError(f"installation key {path} is not readable: {e}") from e
        except OSError as e:
            raise InstallationKeyError(f"installation key {path} cannot be read: {e}") from e
        return cls.parse(text)

    def write(self, path: Path, *, overwrite: bool = False) -> None:
        """Write the key as hex, mode 0640, never replacing an existing file
        unless asked (a replaced key makes every encrypted value unreadable)."""
        if path.exists() and not overwrite:
            raise InstallationKeyError(f"{path} already exists; refusing to overwrite it")
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_name(f".{path.name}.tmp-{os.getpid()}")
        fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, KEY_FILE_MODE)
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as fh:
                fh.write(self.hex + "\n")
                fh.flush()
                os.fsync(fh.fileno())
            os.chmod(tmp, KEY_FILE_MODE)
            os.replace(tmp, path)
        except BaseException:
            tmp.unlink(missing_ok=True)
            raise

    @property
    def hex(self) -> str:
        return self._raw.hex()

    @property
    def fingerprint(self) -> str:
        """Short identifier safe to log or compare between HA nodes."""
        return hashlib.sha256(self._raw).hexdigest()[:16]

    # --- encryption ------------------------------------------------------------

    def encrypt(self, plaintext: str, purpose: str) -> str:
        nonce = os.urandom(NONCE_BYTES)
        sealed = self._aead.encrypt(nonce, plaintext.encode("utf-8"), purpose.encode("utf-8"))
        return f"{TOKEN_VERSION}:" + base64.urlsafe_b64encode(nonce + sealed).decode("ascii")

    def decrypt(self, token: str, purpose: str) -> str:
        version, _, payload = token.partition(":")
        if version != TOKEN_VERSION or not payload:
            raise DecryptionError("unsupported or malformed ciphertext")
        try:
            data = base64.urlsafe_b64decode(payload.encode("ascii"))
        except (binascii.Error, ValueError) as e:
            raise DecryptionError("malformed ciphertext") from e
        if len(data) <= NONCE_BYTES:
            raise DecryptionError("malformed ciphertext")
        try:
            clear = self._aead.decrypt(data[:NONCE_BYTES], data[NONCE_BYTES:], purpose.encode())
        except InvalidTag as e:
            raise DecryptionError(
                "the value cannot be decrypted with this installation key for this purpose"
            ) from e
        return clear.decode("utf-8")


def is_encrypted_token(value: str | None) -> bool:
    return bool(value) and str(value).startswith(f"{TOKEN_VERSION}:")


# ----------------------------------------------------------------- loading

_cache: dict[Path, tuple[tuple[int, int], InstallationKey]] = {}


def load_installation_key(settings: Settings) -> InstallationKey:
    """The installation key named by the settings, re-read when the file changes."""
    path = settings.installation_key_path
    try:
        st = os.stat(path)
    except OSError as e:
        _cache.pop(path, None)
        raise InstallationKeyError(
            f"installation key {path} does not exist (the installer creates it; "
            "'veyra installation-key generate' creates one by hand)"
        ) from e
    stamp = (st.st_mtime_ns, st.st_size)
    cached = _cache.get(path)
    if cached and cached[0] == stamp:
        return cached[1]
    key = InstallationKey.load(path)
    _cache[path] = (stamp, key)
    return key


def try_load_installation_key(settings: Settings) -> InstallationKey | None:
    try:
        return load_installation_key(settings)
    except InstallationKeyError:
        return None
