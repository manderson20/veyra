"""The migrations and the models agree: what CI runs as ``alembic check``,
here against the test database so a drift is caught before a push."""

from __future__ import annotations

from pathlib import Path

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

import veyra


def test_migrations_match_models(database_url: str) -> None:
    cfg = Config()
    cfg.set_main_option("script_location", str(Path(veyra.__file__).parent / "migrations"))
    cfg.set_main_option("sqlalchemy.url", database_url)
    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as e:  # pragma: no cover - the message is the point
        raise AssertionError(f"the models drifted from the migrations: {e}") from e
